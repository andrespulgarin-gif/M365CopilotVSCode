#!/usr/bin/env node
/**
 * Bundles src/main.ts — and everything it imports, @m365copilot/core included
 * — into dist/m365-copilot-tui.mjs: one file that only needs Node, so the TUI
 * runs on its own, without this repository.
 *
 *   node scripts/build.mjs            write dist/m365-copilot-tui.mjs
 *   node scripts/build.mjs --check    exit 1 if dist/ is out of date
 */
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "tsdown";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT_DIR = join(ROOT, "dist");
const OUTPUT = join(OUT_DIR, "m365-copilot-tui.mjs");

export async function buildTui() {
  const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  const staging = mkdtempSync(join(tmpdir(), "m365-tui-"));
  try {
    await build({
      config: false,
      cwd: ROOT,
      entry: { "m365-copilot-tui": join(ROOT, "src", "main.ts") },
      format: "esm",
      platform: "node",
      target: "es2022",
      outDir: staging,
      outExtensions: () => ({ js: ".mjs" }),
      dts: false,
      sourcemap: false,
      minify: false,
      clean: false,
      hash: false,
      logLevel: "warn",
      tsconfig: join(ROOT, "tsconfig.json"),
      // `ws` and the core contracts travel inside the bundle; the optional
      // native speedups of `ws` stay external (it requires them in a try/catch),
      // and so does @opentui/core: its renderer is a native (Zig) addon shipped
      // per platform, resolved from node_modules at runtime.
      deps: {
        alwaysBundle: ["ws", "@m365copilot/core"],
        neverBundle: ["@opentui/core", "bufferutil", "utf-8-validate"],
      },
      define: { "process.env.M365_TUI_VERSION": JSON.stringify(version) },
      banner:
        "#!/usr/bin/env node\n" +
        "// GENERATED by packages/tui/scripts/build.mjs from src/ — do not edit\n" +
        "// by hand: run `pnpm build` in packages/tui.",
    });
    return readFileSync(join(staging, "m365-copilot-tui.mjs"), "utf8").replace(/\r\n/g, "\n");
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const fresh = await buildTui();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8").replace(/\r\n/g, "\n");
    } catch {
      /* missing counts as stale */
    }
    if (current !== fresh) {
      console.error("dist/m365-copilot-tui.mjs is out of date: run `pnpm build` in packages/tui.");
      process.exit(1);
    }
    console.log("dist/m365-copilot-tui.mjs is up to date.");
  } else {
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(OUTPUT, fresh);
    console.log(`dist/m365-copilot-tui.mjs written (${Math.round(fresh.length / 1024)} KB).`);
  }
}
